#!/usr/bin/env python3
"""Generate the optional helper from its canonical embedded implementation."""
from pathlib import Path
import argparse

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source = (root / 'AHK_FOR_GOS_BY_SBEZRUK.ahk').read_text(encoding='cp1251')
start = '; ===== BEGIN EMBEDDED helper.ahk: territory map quality/forum patch =====\n'
end = '; ===== END EMBEDDED helper.ahk ====='
body = source.split(start, 1)[1].split(end, 1)[0]
header = '; Generated by tools/sync_helper.py from the embedded helper in the main script.\n; Do not include this file together with the main script: its functions are already embedded.\n'
expected = (header + body).replace('\n', '\r\n').encode('cp1251')
target = root / 'helper.ahk'
if args.check:
    if not target.exists() or target.read_bytes() != expected:
        raise SystemExit('helper.ahk is out of sync; run python tools/sync_helper.py')
    print('helper.ahk matches its canonical embedded implementation')
else:
    target.write_bytes(expected)
    print('Updated helper.ahk')
